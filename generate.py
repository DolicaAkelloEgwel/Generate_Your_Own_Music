import argparse
import json
import os
from pathlib import Path

import numpy as np
from music21 import chord, instrument, note, stream
from tensorflow.keras.models import load_model

from constants import LATENT_DIMENSION

args = argparse.ArgumentParser()

args.add_argument(
    "-m",
    "--models",
    required=True,
    help="path to the folder containing the model files produced from the training",
)

args.add_argument(
    "-ld",
    "--latent-dimension",
    type=int,
    default=LATENT_DIMENSION,
)

args.add_argument(
    "-o",
    "--output",
    required=True,
    help="output filename without extension for the generated midi file(s)",
)

args.add_argument(
    "-n",
    "--number",
    type=int,
    default=1,
    help="the number of files to generate",
)

args = args.parse_args()

instr = instrument.Violin()


def create_midi(prediction_output, filename):
    """convert the output from the prediction to notes and create a midi file
    from the notes"""
    offset = 0
    output_notes = []

    # create note and chord objects based on the values generated by the model
    for item in prediction_output:
        pattern = item[0]
        # pattern is a chord
        if ("." in pattern) or pattern.isdigit():
            notes_in_chord = pattern.split(".")
            notes = []
            for current_note in notes_in_chord:
                new_note = note.Note(int(current_note))
                new_note.storedInstrument = instr
                notes.append(new_note)
            new_chord = chord.Chord(notes)
            new_chord.offset = offset
            output_notes.append(new_chord)
        # pattern is a note
        else:
            new_note = note.Note(pattern)
            new_note.offset = offset
            new_note.storedInstrument = instr
            output_notes.append(new_note)

        # increase offset each iteration so that notes do not stack
        offset += 0.5

    midi_stream = stream.Stream(output_notes)
    midi_stream.write("midi", fp=f"{filename}.mid")


def generate_music(generator_model, latent_dim, n_vocab, pitch_names, length=500):
    """Generate new music using the trained generator model"""
    # Create random noise as input to the generator
    noise = np.random.normal(0, 1, (1, latent_dim))
    predictions = generator_model.predict(noise)

    # Scale back the predictions to the original range
    pred_notes = [x * (n_vocab / 2) + (n_vocab / 2) for x in predictions[0]]

    # Map generated integer indices to note names
    int_to_note = {number: note for number, note in enumerate(pitch_names)}
    pred_notes_mapped = [int_to_note[int(x)] for x in pred_notes]

    return pred_notes_mapped[:length]


# Load the trained generator model
generator_model = load_model(f"{args.models}/generator.h5")

# Load the processed notes and get the number of unique pitches
with open(f"{args.models}/meta.json", "r") as f:
    data = json.load(f)

n_vocab = data["n-vocab"]
pitch_names = set(data["pitch-names"])

p = Path(args.output)

if not os.path.isdir(p.parent):
    os.mkdir(p.parent)

if args.number == 1:
    generated_music = generate_music(
        generator_model, args.latent_dimension, n_vocab, pitch_names
    )
    create_midi(generated_music, args.output)
else:
    digits = len(str(args.number))
    for i in range(args.number):
        generated_music = generate_music(
            generator_model, args.latent_dimension, n_vocab, pitch_names
        )
        create_midi(generated_music, f"{args.output}-{i:0{digits}d}")
